/**
 * The character set of the PronounceAll Phonetic web font (FR-IPA-09,
 * NFR-PERF-03; Frontend Baseline §4.2; maintainer decision 2026-10-01).
 *
 * Generated from the content that renders in the IPA font, never from what the
 * source font happens to support:
 *   - the D4 artifact (data/seed/en-us.phonemes.json): every teaching unit's
 *     symbol and its example's phonemic transcription;
 *   - the stored corpus: every pronunciation's transcription and syllable
 *     breakdown, every phoneme symbol and example transcription;
 *   - the characters templates put inside IPA elements (the `/` delimiters and
 *     the space), and the marks the transcription convention uses: primary and
 *     secondary stress and the syllable dot.
 *
 * The output, tools/fonts/pronounceall-phonetic.charset.txt, is committed; the
 * font build reads only that file. Rerun this after seeding new content, then
 * rebuild the font: the coverage test fails until both are done.
 *
 * Usage: npm run fonts:charset
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { closePool, getPool } from '../src/lib/mysql.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CHARSET_FILE = path.join(ROOT, 'tools', 'fonts', 'pronounceall-phonetic.charset.txt');
const D4_ARTIFACT = path.join(ROOT, 'data', 'seed', 'en-us.phonemes.json');

/** Characters the templates and the transcription convention add. */
export const TEMPLATE_CHARACTERS = Object.freeze({
  '/': 'phonemic delimiters around every transcription',
  ' ': 'space',
  'ˈ': 'primary stress',
  'ˌ': 'secondary stress',
  '.': 'syllable separator',
});

/** Columns whose text renders in an IPA element. */
const CORPUS_QUERIES = Object.freeze({
  'word_pronunciations.ipa_transcription': 'SELECT ipa_transcription AS text FROM word_pronunciations',
  'word_pronunciations.syllable_breakdown': 'SELECT syllable_breakdown AS text FROM word_pronunciations',
  'phonemes.ipa_symbol': 'SELECT ipa_symbol AS text FROM phonemes',
  'phoneme_example_words.phonemic_transcription': 'SELECT phonemic_transcription AS text FROM phoneme_example_words',
});

/** @param {Map<string, Set<string>>} sources @param {string} text @param {string} source */
function add(sources, text, source) {
  for (const character of String(text ?? '')) {
    if (!sources.has(character)) sources.set(character, new Set());
    sources.get(character).add(source);
  }
}

/** @returns {Promise<Map<string, Set<string>>>} character → where it was found */
export async function collectPhoneticCharacters(executor = getPool()) {
  const sources = new Map();
  for (const [character, why] of Object.entries(TEMPLATE_CHARACTERS)) add(sources, character, `template: ${why}`);
  const d4 = JSON.parse(await readFile(D4_ARTIFACT, 'utf8'));
  for (const unit of d4.units) {
    add(sources, unit.ipaSymbol, 'D4 ipaSymbol');
    add(sources, unit.phonemicTranscription, 'D4 phonemicTranscription');
  }
  for (const [source, sql] of Object.entries(CORPUS_QUERIES)) {
    const [rows] = await executor.query(sql);
    for (const row of rows) add(sources, row.text, source);
  }
  return sources;
}

/** One line per character: code point, the character, and its sources. */
export function formatCharset(sources) {
  const lines = [...sources.entries()]
    .sort(([a], [b]) => a.codePointAt(0) - b.codePointAt(0))
    .map(([character, from]) => {
      const code = `U+${character.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')}`;
      const shown = character === ' ' ? '(space)' : character;
      return `${code}\t${shown}\t${[...from].sort().join('; ')}`;
    });
  return `# PronounceAll Phonetic character set. Generated by scripts/generate-phonetic-charset.js; do not edit.\n${lines.join('\n')}\n`;
}

async function main() {
  const sources = await collectPhoneticCharacters();
  await writeFile(CHARSET_FILE, formatCharset(sources), 'utf8');
  process.stdout.write(`Wrote ${sources.size} characters to ${path.relative(ROOT, CHARSET_FILE)}.\n`);
}

if (process.argv[1]?.endsWith('generate-phonetic-charset.js')) {
  main()
    .catch((error) => {
      process.stderr.write(`${error.stack}\n`);
      process.exitCode = 1;
    })
    .finally(closePool);
}
